#!/usr/bin/env python3
"""Frozen V20 consequence-symmetry developmental kernel.

The kernel knows no geometry or named symmetry. It receives only a complete
finite consequence table and a generic finite bijection language generated by
label transpositions under composition.
"""
from __future__ import annotations

from dataclasses import dataclass
import itertools
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from basis import (
    ConsequenceWorld,
    Transform,
    all_transforms,
    compose_transform,
    identity_transform,
    inverse_transform,
    is_consequence_symmetry,
    is_identity,
    transform_cost,
)


@dataclass(frozen=True)
class CompiledSymmetry:
    interface_key: Tuple[int, int]
    generators: Tuple[Transform, ...]
    group: Tuple[Transform, ...]
    cell_orbits: Tuple[Tuple[Tuple[int, int], ...], ...]
    representative_values: Tuple[int, ...]
    provenance: Tuple[str, ...]

    def data(self) -> Any:
        return {
            "interface_key": list(self.interface_key),
            "generators": [g.data() for g in self.generators],
            "group_order": len(self.group),
            "cell_orbit_sizes": [len(o) for o in self.cell_orbits],
            "representative_values": list(self.representative_values),
            "provenance": list(self.provenance),
        }


class Kernel:
    @staticmethod
    def _authority(world: ConsequenceWorld) -> Optional[Dict[str, Any]]:
        if not world.complete:
            return {
                "status": "UNKNOWN_AUTHORITY",
                "reason": "consequence_table_incomplete",
            }
        return None

    @staticmethod
    def _closure(
        generators: Sequence[Transform],
        n: int,
        m: int,
    ) -> Tuple[Transform, ...]:
        ident = identity_transform(n, m)
        closed = {ident}
        frontier = [ident]

        basis = set(generators)
        basis.update(inverse_transform(g) for g in generators)

        for g in basis:
            if g not in closed:
                closed.add(g)
                frontier.append(g)

        while frontier:
            a = frontier.pop()
            snapshot = list(closed)
            for b in snapshot:
                for c in (
                    compose_transform(a, b),
                    compose_transform(b, a),
                ):
                    if c not in closed:
                        closed.add(c)
                        frontier.append(c)

        return tuple(sorted(closed))

    @staticmethod
    def _orbits_on_labels(
        group: Sequence[Transform],
        count: int,
        side: str,
    ) -> Tuple[Tuple[int, ...], ...]:
        unseen = set(range(count))
        out: List[Tuple[int, ...]] = []
        while unseen:
            seed = min(unseen)
            if side == "states":
                orbit = {g.states[seed] for g in group}
            elif side == "tests":
                orbit = {g.tests[seed] for g in group}
            else:
                raise ValueError(side)
            row = tuple(sorted(orbit))
            out.append(row)
            unseen.difference_update(orbit)
        out.sort(key=lambda x: (len(x), x))
        return tuple(out)

    @staticmethod
    def _cell_orbits(
        group: Sequence[Transform],
        n: int,
        m: int,
    ) -> Tuple[Tuple[Tuple[int, int], ...], ...]:
        unseen = {(x, c) for x in range(n) for c in range(m)}
        out: List[Tuple[Tuple[int, int], ...]] = []
        while unseen:
            seed = min(unseen)
            x, c = seed
            orbit = {
                (g.states[x], g.tests[c])
                for g in group
            }
            row = tuple(sorted(orbit))
            out.append(row)
            unseen.difference_update(orbit)
        out.sort(key=lambda x: (len(x), x))
        return tuple(out)

    @staticmethod
    def _representatives_and_reconstruct(
        world: ConsequenceWorld,
        cell_orbits: Sequence[Sequence[Tuple[int, int]]],
    ) -> Dict[str, Any]:
        values: List[int] = []
        reconstructed = [
            [None for _ in range(world.test_count)]
            for _ in range(world.state_count)
        ]
        orbit_rows = []

        for orbit in cell_orbits:
            rep = tuple(orbit[0])
            value = world.consequence(rep[0], rep[1])
            if value is None:
                return {
                    "status": "UNKNOWN_AUTHORITY",
                }

            constant = all(
                world.consequence(x, c) == value
                for x, c in orbit
            )
            if not constant:
                return {
                    "status": "INVALID_ORBIT",
                    "orbit": [list(z) for z in orbit],
                }

            values.append(int(value))
            for x, c in orbit:
                reconstructed[x][c] = int(value)

            orbit_rows.append({
                "representative": list(rep),
                "value": int(value),
                "size": len(orbit),
                "cells": [list(z) for z in orbit],
            })

        exact = tuple(tuple(int(v) for v in row) for row in reconstructed) == world.table

        return {
            "status": "VERIFIED" if exact else "RECONSTRUCTION_FAILED",
            "representative_values": values,
            "orbit_rows": orbit_rows,
            "reconstructed_table": reconstructed,
            "exact_reconstruction": exact,
        }

    def _minimum_generator_frontier(
        self,
        group: Sequence[Transform],
        n: int,
        m: int,
    ) -> Dict[str, Any]:
        target = set(group)
        ident = identity_transform(n, m)

        if target == {ident}:
            return {
                "status": "VERIFIED",
                "minimum_generator_count": 0,
                "minimum_total_transposition_cost": 0,
                "frontier": [[]],
            }

        nonidentity = [g for g in group if not is_identity(g)]

        for k in range(1, len(nonidentity) + 1):
            successful = []
            best_cost = None

            for combo in itertools.combinations(nonidentity, k):
                if set(self._closure(combo, n, m)) != target:
                    continue

                cost = sum(transform_cost(g) for g in combo)
                if best_cost is None or cost < best_cost:
                    best_cost = cost
                    successful = [combo]
                elif cost == best_cost:
                    successful.append(combo)

            if successful:
                successful.sort()
                return {
                    "status": "VERIFIED",
                    "minimum_generator_count": k,
                    "minimum_total_transposition_cost": int(best_cost),
                    "frontier": [
                        [g.data() for g in combo]
                        for combo in successful
                    ],
                    "_frontier_objects": tuple(successful),
                }

        return {
            "status": "CERTIFIED_NO_GENERATOR_BASIS",
            "frontier": [],
        }

    @staticmethod
    def _structural_signature(
        world: ConsequenceWorld,
        group: Sequence[Transform],
        state_orbits: Sequence[Sequence[int]],
        test_orbits: Sequence[Sequence[int]],
        cell_orbits: Sequence[Sequence[Tuple[int, int]]],
        representatives: Dict[str, Any],
        generators: Dict[str, Any],
    ) -> Dict[str, Any]:
        cell_signature = []
        for orbit, value in zip(
            cell_orbits,
            representatives["representative_values"],
        ):
            cell_signature.append([len(orbit), int(value)])
        cell_signature.sort()

        return {
            "interface": [world.state_count, world.test_count],
            "group_order": len(group),
            "state_orbit_sizes": sorted(len(o) for o in state_orbits),
            "test_orbit_sizes": sorted(len(o) for o in test_orbits),
            "cell_orbit_size_value_multiset": cell_signature,
            "minimum_generator_count": generators.get(
                "minimum_generator_count"
            ),
            "minimum_total_transposition_cost": generators.get(
                "minimum_total_transposition_cost"
            ),
        }

    def analyze(
        self,
        world: ConsequenceWorld,
        *,
        consequence_enabled: bool = True,
        composition_enabled: bool = True,
        retain_nontrivial: bool = True,
    ) -> Dict[str, Any]:
        auth = self._authority(world)
        if auth:
            return auth

        ident = identity_transform(world.state_count, world.test_count)

        if not consequence_enabled:
            return {
                "status": "UNKNOWN_NO_CONSEQUENCE_AUTHORITY",
                "candidate_count": 1,
                "verified_transformations": [ident.data()],
                "symmetry_count": 1,
            }

        candidates = []
        for t in all_transforms(world.state_count, world.test_count):
            if composition_enabled or transform_cost(t) <= 1:
                candidates.append(t)

        verified = [
            t for t in candidates
            if is_consequence_symmetry(world, t)
        ]

        if ident not in verified:
            raise AssertionError("identity must preserve complete consequence")

        full_verified = verified
        if not retain_nontrivial:
            verified = [ident]

        verified_tuple = tuple(sorted(set(verified)))

        if not composition_enabled:
            return {
                "status": "PARTIAL_TRANSFORMATION_LANGUAGE",
                "candidate_count": len(candidates),
                "verified_transformations": [t.data() for t in verified_tuple],
                "symmetry_count": len(verified_tuple),
                "max_verified_cost": max(
                    transform_cost(t) for t in verified_tuple
                ),
                "composition_enabled": False,
            }

        closure = self._closure(
            verified_tuple,
            world.state_count,
            world.test_count,
        )
        closed_exactly = set(closure) == set(verified_tuple)

        state_orbits = self._orbits_on_labels(
            closure, world.state_count, "states"
        )
        test_orbits = self._orbits_on_labels(
            closure, world.test_count, "tests"
        )
        cell_orbits = self._cell_orbits(
            closure, world.state_count, world.test_count
        )

        reps = self._representatives_and_reconstruct(
            world, cell_orbits
        )
        generators = self._minimum_generator_frontier(
            closure,
            world.state_count,
            world.test_count,
        )

        if reps.get("status") != "VERIFIED":
            return {
                "status": reps.get("status"),
                "candidate_count": len(candidates),
                "symmetry_count": len(closure),
                "representatives": reps,
            }

        signature = self._structural_signature(
            world,
            closure,
            state_orbits,
            test_orbits,
            cell_orbits,
            reps,
            generators,
        )

        return {
            "status": "VERIFIED",
            "candidate_count": len(candidates),
            "verified_transformations": [t.data() for t in verified_tuple],
            "_group_objects": closure,
            "symmetry_count": len(closure),
            "closed_exactly": closed_exactly,
            "state_orbits": [list(o) for o in state_orbits],
            "test_orbits": [list(o) for o in test_orbits],
            "cell_orbits": [
                [list(z) for z in orbit]
                for orbit in cell_orbits
            ],
            "cell_orbit_count": len(cell_orbits),
            "raw_cell_count": world.cell_count,
            "compression_ratio": (
                world.cell_count / len(cell_orbits)
            ),
            "representatives": reps,
            "generator_search": {
                k: v
                for k, v in generators.items()
                if not k.startswith("_")
            },
            "_generator_frontier_objects": generators.get(
                "_frontier_objects", tuple()
            ),
            "structural_signature": signature,
            "max_verified_cost": max(
                transform_cost(t) for t in closure
            ),
            "composition_enabled": True,
            "retained_nontrivial": retain_nontrivial,
        }

    def compile(
        self,
        world: ConsequenceWorld,
        analysis: Dict[str, Any],
        *,
        provenance: Sequence[str],
    ) -> CompiledSymmetry:
        if analysis.get("status") != "VERIFIED":
            raise ValueError("only verified analysis may compile")

        frontier = analysis.get("_generator_frontier_objects", tuple())
        if not frontier:
            generators: Tuple[Transform, ...] = tuple()
        else:
            # Preserve frontier in evidence, but active compiled execution may
            # use the first equal-cost basis. Exact group/replay remains the
            # authority, so this does not delete warranted alternatives.
            generators = tuple(frontier[0])

        group = tuple(analysis["_group_objects"])
        cell_orbits = tuple(
            tuple((int(x), int(c)) for x, c in orbit)
            for orbit in analysis["cell_orbits"]
        )
        values = tuple(
            int(v)
            for v in analysis["representatives"]["representative_values"]
        )

        return CompiledSymmetry(
            interface_key=world.interface_key(),
            generators=generators,
            group=group,
            cell_orbits=cell_orbits,
            representative_values=values,
            provenance=tuple(provenance),
        )

    def replay_compiled(
        self,
        world: ConsequenceWorld,
        compiled: CompiledSymmetry,
    ) -> Dict[str, Any]:
        auth = self._authority(world)
        if auth:
            return auth

        if compiled.interface_key != world.interface_key():
            return {
                "status": "TYPE_MISMATCH",
            }

        failed = [
            g for g in compiled.group
            if not is_consequence_symmetry(world, g)
        ]

        reconstructed = [
            [None for _ in range(world.test_count)]
            for _ in range(world.state_count)
        ]
        for orbit, value in zip(
            compiled.cell_orbits,
            compiled.representative_values,
        ):
            for x, c in orbit:
                reconstructed[x][c] = value

        exact_old_quotient = (
            tuple(tuple(int(v) for v in row) for row in reconstructed)
            == world.table
        )

        return {
            "status": (
                "VERIFIED"
                if not failed and exact_old_quotient
                else "REPLAY_FAILED"
            ),
            "failed_transformation_count": len(failed),
            "failed_transformations": [g.data() for g in failed],
            "old_quotient_exact": exact_old_quotient,
            "reconstructed_table": reconstructed,
        }
