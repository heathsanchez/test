#!/usr/bin/env python3
from __future__ import annotations

import sys
from pathlib import Path

import sair_residual_constrained_transformer_v32 as core


def _arg_value(flag: str) -> str:
    try:
        i = sys.argv.index(flag)
    except ValueError as exc:
        raise SystemExit(f"missing required argument {flag}") from exc
    try:
        return sys.argv[i + 1]
    except IndexError as exc:
        raise SystemExit(f"missing value for {flag}") from exc


SAIR_ROOT = Path(_arg_value("--sair-root"))


class LazySAIRRuntimeAdapter(core.SAIRRuntimeAdapter):
    """Infrastructure repair for V32-generated probes.

    V32's frozen raw transformer carrier may construct atomic probes that were not
    present in the V28 static observation cache. Such probes must be executed by
    the same exact bounded-model verifier rather than failing a lookup or being
    assigned a guessed value. This changes only the execution interface; the
    transformer carrier, K_meta constraints, router, and scientific gates remain
    frozen.
    """

    def probe_outcome(self, state, world_id: int, probe_id: str):
        row = self.rows[world_id]
        program = self.programs[probe_id]
        if program.get("kind") == "atom" and probe_id not in row["atom_values"]:
            order = int(program["order"])
            direction = str(program["direction"])
            audit = core.ensure_exact_order_values(
                SAIR_ROOT,
                self.rows,
                {world_id},
                order,
                direction,
            )
            if audit["bad"] or audit["unknown"]:
                raise RuntimeError(
                    f"generated probe verifier failure for {probe_id} on world {world_id}: {audit}"
                )
        return super().probe_outcome(state, world_id, probe_id)


# Preserve the frozen V32 experiment while repairing only the adapter's ability to
# execute previously absent probes generated by its already-precommitted carrier.
core.SAIRRuntimeAdapter = LazySAIRRuntimeAdapter


if __name__ == "__main__":
    core.main()
